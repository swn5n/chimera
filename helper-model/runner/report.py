#!/usr/bin/env python3
"""Collect every run's summary into results/BASELINES.md (the latest run per model and settings).

    python3 runner/report.py [--runs results/runs] [--out results/BASELINES.md]
    python3 runner/report.py --eval-dir eval/archive/v0-draft --out results/BASELINES-v0.md

Only runs on the chosen eval set's version count (by default the current one in eval/).

Also adds the gate's no-model row: Chimera's own word rule, worked out from the eval set alone.
"""
from __future__ import annotations

import argparse
import glob
import json
import os
import sys

HERE = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
if HERE not in sys.path:
    sys.path.insert(0, HERE)

from helper import chimera_port as cp  # noqa: E402
from helper import evalset  # noqa: E402
from runner import scoring  # noqa: E402


def label(m):
    """The model, with the experiment's name if the run was one (not Chimera's own request)."""
    return m["model"] + (f" [{m['variant']}]" if m.get("variant") else "") + \
        (f" (temperature {m['temperature']})" if m.get("temperature") not in (None, "unset") else "")


def pc(x):
    return "–" if x is None else f"{100 * x:.0f}%"


def sec(x):
    return "–" if x is None else f"{x:.1f}"


def word_rule_row(es):
    scores = []
    for p, g, h in es.gate_pairs():
        reach = cp.reaches_gate(p["prompt"], h)
        use = bool(reach[0] and reach[1] >= cp.WORD_RULE_MIN)
        scores.append({"use": use, "expected": g["use"], "correct": use == g["use"], "confidence": g["confidence"],
                       "reaches": reach[0], "pipeline_correct": use == g["use"], "word_rule_correct": use == g["use"]})
    return scoring.gate_counts(scores)


def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--runs", default=os.path.join(HERE, "results", "runs"))
    ap.add_argument("--out", default=os.path.join(HERE, "results", "BASELINES.md"))
    ap.add_argument("--eval-dir", default=evalset.EVAL_DIR, help="the eval set whose runs to report (default: eval/)")
    a = ap.parse_args(argv)
    es = evalset.load(a.eval_dir)
    es_version = es.version
    latest = {}
    for path in sorted(glob.glob(os.path.join(a.runs, "*", "summary.json"))):
        with open(path, encoding="utf-8") as f:
            doc = json.load(f)
        m = doc["meta"]
        if m.get("limit"):
            continue  # smoke runs don't count
        if m["eval_version"] != es_version:
            continue  # only runs on the current eval set
        key = (m["model"], m["think"], m.get("variant"), m.get("temperature", "unset"), m["seed"], m["eval_version"],
               ",".join(m["jobs"]))
        latest[key] = (os.path.basename(os.path.dirname(path)), doc)
    runs = sorted(latest.values(), key=lambda x: x[0])
    L = ["# Baselines on the helper eval", "",
         f"Eval {es.version}. Each row is the latest full run of a model with those settings; raw replies are in "
         "`results/runs/<run>/raw.jsonl`. Settings match Chimera's requests except where noted "
         "(a fixed seed; `think` only if set). *Valid after tidying* applies only format fixes: the JSON object without "
         "fences or prose, step ids renamed s1..sN, empty depends_on lists filled in. Generated by `runner/report.py`.", ""]
    if not runs:
        older = sorted(os.path.basename(p) for p in glob.glob(os.path.join(os.path.dirname(a.out), "BASELINES-*.md")))
        L += [f"No full model runs on {es.version} yet (`bash run_baselines.sh` makes them)." +
              (" Earlier eval versions: " + ", ".join(f"`{o}`" for o in older) + "." if older else ""), ""]
    P = [(r, d) for r, d in runs if "planner" in d["summary"]]
    if P:
        L += ["## Planner", "", "| model | think | accepted by Chimera | strictly valid | valid after tidying | quality | coverage | step count ok | parallel ok | mean steps | p50 s | p95 s | thinks |",
              "|---|---|---|---|---|---|---|---|---|---|---|---|---|"]
        for r, d in P:
            s, m = d["summary"]["planner"], d["meta"]
            L.append(f"| {label(m)} | {m['think']} | {pc(s['chimera_ok'])} | {pc(s['valid'])} | {pc(s.get('valid_tidied'))} | {s['quality']:.2f} | {pc(s['coverage'])} | "
                     f"{pc(s['steps_ok'])} | {pc(s['parallel_ok'])} | {'–' if s['steps_mean'] is None else format(s['steps_mean'], '.1f')} | "
                     f"{sec(s['latency_p50_s'])} | {sec(s['latency_p95_s'])} | {pc(s['thinks'])} |")
        L.append("")
    R = [(r, d) for r, d in runs if "reviewer" in d["summary"]]
    if R:
        L += ["## Reviewer", "", "| model | think | accepted | strictly valid | done right | flawed caught | good accepted | main flaw named | p50 s |",
              "|---|---|---|---|---|---|---|---|---|"]
        for r, d in R:
            s, m = d["summary"]["reviewer"], d["meta"]
            L.append(f"| {label(m)} | {m['think']} | {pc(s['chimera_ok'])} | {pc(s['valid'])} | {pc(s['done_accuracy'])} | {pc(s['flaws_caught'])} | "
                     f"{pc(s['good_accepted'])} | {pc(s['main_flaw_named'])} | {sec(s['latency_p50_s'])} |")
        L.append("")
    wr = word_rule_row(es)
    G = [(r, d) for r, d in runs if "gate" in d["summary"]]
    L += ["## Head gate", "", "Confident pairs only. *Path* = Chimera's word filter, then the gate's answer (what a user actually gets).", "",
          "| model | think | accepted | strictly valid | accuracy | precision | recall | path accuracy | p50 s | p95 s | over 8 s |",
          "|---|---|---|---|---|---|---|---|---|---|---|",
          f"| *word rule only (no model)* | – | – | – | {pc(wr['accuracy'])} | {pc(wr['precision'])} | {pc(wr['recall'])} | {pc(wr['accuracy'])} | – | – | – |"]
    for r, d in G:
        s, m = d["summary"]["gate"], d["meta"]
        L.append(f"| {label(m)} | {m['think']} | {pc(s['chimera_ok'])} | {pc(s['valid'])} | {pc(s['accuracy'])} | {pc(s['precision'])} | "
                 f"{pc(s['recall'])} | {pc(s['pipeline_accuracy'])} | {sec(s['latency_p50_s'])} | {sec(s['latency_p95_s'])} | {s['over_8s']} |")
    L.append("")
    E = [(r, d) for r, d in runs if "embed" in d["summary"]]
    if E:
        L += ["## Zero-shot embedding check", "", "| model | gate AUC | nearest-kind accuracy |", "|---|---|---|"]
        for r, d in E:
            s, m = d["summary"]["embed"], d["meta"]
            L.append(f"| {label(m)} | {s['gate_auc']:.2f} | {pc(s['kind_accuracy'])} |")
        L.append("")
    os.makedirs(os.path.dirname(a.out), exist_ok=True)
    with open(a.out, "w", encoding="utf-8") as f:
        f.write("\n".join(L) + "\n")
    print("wrote", os.path.relpath(a.out, HERE), f"({len(runs)} runs)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
