class TrainHelperTests(unittest.TestCase):
    def setUp(self):
        self.tmp = tempfile.mkdtemp(prefix="hm-train-")

    def tearDown(self):
        shutil.rmtree(self.tmp, ignore_errors=True)

    def test_config(self):
        data = os.path.join(self.tmp, "sft")
        os.makedirs(data)
        for name, n in (("train.jsonl", 10), ("valid.jsonl", 2)):
            with open(os.path.join(data, name), "w") as f:
                f.write("\n".join(json.dumps({"messages": []}) for _ in range(n)) + "\n")
        out = os.path.join(self.tmp, "run", "lora.yaml")
        buf = io.StringIO()
        with contextlib.redirect_stdout(buf):
            self.assertEqual(make_config.main(["--data", data, "--adapters", os.path.join(self.tmp, "run", "adapters"), "--out", out,
                                               "--epochs", "2", "--lr", "3e-5"]), 0)
        info = json.loads(buf.getvalue())
        self.assertEqual(info, {"iters": 5, "train_lines": 10, "valid_lines": 2})
        text = open(out).read()
        for line in ('model: "Qwen/Qwen3-4B-Instruct-2507"', "iters: 5", "num_layers: 36", "mask_prompt: true",
                     "grad_checkpoint: true", "max_seq_length: 8192", "  rank: 16", "learning_rate: 3.00e-05", "  name: cosine_decay"):
            self.assertIn(line, text)
        self.assertIn("  arguments: [3.00e-05, 4, 2.00e-06]", text)  # warmup 1 of 5 steps, then cosine to the end
        import re
        for m in re.finditer(r"\d(\.\d+)?e-\d+", text):  # every exponent float has a decimal point
            self.assertIn(".", m.group(0), m.group(0))

    def test_config_needs_both_files(self):
        with contextlib.redirect_stderr(io.StringIO()):
            self.assertEqual(make_config.main(["--data", self.tmp, "--adapters", "a", "--out", os.path.join(self.tmp, "x.yaml")]), 2)

    def test_modelfile_keeps_template_and_licence(self):
        base = os.path.join(self.tmp, "base.Modelfile")
        with open(base, "w") as f:
            f.write(BASE_MODELFILE)
        out = os.path.join(self.tmp, "Modelfile")
        self.assertEqual(make_modelfile.main(["--base", base, "--from", "/models/fused", "--out", out]), 0)
        text = open(out).read()
        self.assertTrue(text.startswith("FROM /models/fused\nTEMPLATE \"\"\""))
        self.assertEqual(text.count("FROM /"), 1)
        self.assertNotIn("sha256-0123abcd", text)
        self.assertIn("PARAMETER stop <|im_end|>", text)
        self.assertIn("# not a comment: inside the licence text", text)  # kept: it's inside the LICENSE block
        self.assertIn("FROM here on, this is still the licence", text)
        self.assertNotIn('Modelfile generated by "ollama show"', text)

    def test_modelfile_parameter_overrides(self):
        base = os.path.join(self.tmp, "base.Modelfile")
        with open(base, "w") as f:
            f.write(BASE_MODELFILE)
        out = os.path.join(self.tmp, "Modelfile")
        self.assertEqual(make_modelfile.main(["--base", base, "--from", "/m.gguf", "--out", out, "--temperature", "0.2",
                                              "--num-predict", "4096"]), 0)
        with open(out) as f:
            text = f.read()
        self.assertIn("PARAMETER temperature 0.2\n", text)
        self.assertNotIn("PARAMETER temperature 0.7", text)
        self.assertEqual(text.count("PARAMETER temperature"), 1)
        self.assertIn("PARAMETER num_predict 4096\n", text)
        self.assertLess(text.index("PARAMETER num_predict"), text.index("LICENSE"))
        self.assertIn("PARAMETER top_k 20", text)
        self.assertIn("FROM here on, this is still the licence", text)  # the licence block is untouched

    def test_unbalanced_quotes_are_an_error(self):
        with self.assertRaises(ValueError):
            make_modelfile.strip_from('TEMPLATE """never closed\nPARAMETER x 1\n')

    def test_new_table_log_parsing(self):
        log = ("Trainable parameters: 0.821% (33.030M/4022.468M)\n"
               "  \x1b[1miter   train_loss     tok/s     tokens\x1b[0m\n"
               "  \x1b[38;5;244m   1\x1b[0m    \x1b[1;35mval\x1b[0m \x1b[1m1.521\x1b[0m    \x1b[38;5;244m48.67s\x1b[0m\n"
               "    10    1.666 \u25bc       99      7.6k\n"
               "    20    0.720 \u25bc      128     19.0k\n"
               "    40    0.953 \u25b2       99     38.9k\n"
               "   100    val 0.512    47.10s\n")
        p = summarize.parse_log(log)
        self.assertEqual(p["train"], [(10, 1.666), (20, 0.72), (40, 0.953)])
        self.assertEqual(p["val"], [(1, 1.521), (100, 0.512)])
        self.assertEqual(p["tokens_per_s"], 109)

    def test_log_parsing(self):
        p = summarize.parse_log(LOG)
        self.assertEqual(p["train"], [(10, 1.65), (20, 0.91)])
        self.assertEqual(p["val"][0], (1, 1.912))
        self.assertEqual(min(p["val"], key=lambda x: x[1]), (200, 0.351))
        self.assertEqual(p["tokens_per_s"], 2456)
        self.assertEqual(p["peak_mem_gb"], 23.01)


def _write_json(folder, name, obj):
    with open(os.path.join(folder, name), "w", encoding="utf-8") as f:
        json.dump(obj, f)


class GgufSourceTests(unittest.TestCase):
    """The folder llama.cpp's converter reads: merged weights linked, tokenizer files in the 4.x form."""
    TOK = {"version": "1.0", "added_tokens": [{"id": 3, "content": "<|im_end|>", "special": True, "normalized": False}],
           "model": {"type": "BPE", "vocab": {"a": 0, "b": 1, "ab": 2}, "merges": [["a", "b"]]}}
    CFG5 = {"backend": "tokenizers", "eos_token": "<|im_end|>", "extra_special_tokens": ["<|im_start|>", "<|im_end|>"],
            "is_local": True, "local_files_only": False, "tokenizer_class": "Qwen2Tokenizer"}
    CFG4 = {"additional_special_tokens": ["<|im_start|>", "<|im_end|>"], "eos_token": "<|im_end|>",
            "tokenizer_class": "Qwen2Tokenizer", "chat_template": "{{ base }}"}

    def setUp(self):
        self.tmp = tempfile.mkdtemp(prefix="hm-gguf-")
        self.fused = os.path.join(self.tmp, "fused")
        self.out = os.path.join(self.tmp, "gguf-src")
        self.hub = os.path.join(self.tmp, "hub")
        os.makedirs(self.fused)
        _write_json(self.fused, "tokenizer.json", self.TOK)
        _write_json(self.fused, "tokenizer_config.json", self.CFG5)
        _write_json(self.fused, "config.json", {"architectures": ["Qwen3ForCausalLM"]})
        with open(os.path.join(self.fused, "model-00001-of-00001.safetensors"), "wb") as f:
            f.write(b"\0" * 16)
        with open(os.path.join(self.fused, "chat_template.jinja"), "w") as f:
            f.write("{{ merged }}")
        for p in (mock.patch.object(gguf_source, "hub_caches", lambda: [self.hub]),
                  mock.patch.object(gguf_source, "downloaded_snapshot", lambda repo: None)):
            p.start()
            self.addCleanup(p.stop)

    def tearDown(self):
        shutil.rmtree(self.tmp, ignore_errors=True)

    def cache_base(self, tok, extra=("vocab.json", "merges.txt"), cfg=None):
        """A Hugging Face cache snapshot of test/base, its files linked to blobs as the real cache does."""
        root = os.path.join(self.hub, "models--test--base")
        snap = os.path.join(root, "snapshots", "abc123")
        blobs = os.path.join(root, "blobs")
        os.makedirs(snap)
        os.makedirs(blobs)
        os.makedirs(os.path.join(root, "refs"))
        with open(os.path.join(root, "refs", "main"), "w") as f:
            f.write("abc123")
        files = {"tokenizer.json": json.dumps(tok), "tokenizer_config.json": json.dumps(cfg or self.CFG4)}
        files.update({n: n for n in extra})
        for i, (name, text) in enumerate(files.items()):
            blob = os.path.join(blobs, f"blob{i}")
            with open(blob, "w") as f:
                f.write(text)
            os.symlink(blob, os.path.join(snap, name))
        return snap

    def build(self):
        with contextlib.redirect_stderr(io.StringIO()) as err:
            how = gguf_source.build("test/base", self.fused, self.out)
        return how, err.getvalue()

    def read_out(self, name):
        with open(os.path.join(self.out, name), encoding="utf-8") as f:
            return f.read()

    def assert_weights_linked(self):
        for name in ("config.json", "model-00001-of-00001.safetensors", "chat_template.jinja"):
            p = os.path.join(self.out, name)
            self.assertTrue(os.path.islink(p), name)
            self.assertEqual(os.path.realpath(p), os.path.realpath(os.path.join(self.fused, name)))
        with open(os.path.join(self.fused, "tokenizer_config.json")) as f:
            self.assertEqual(json.load(f), self.CFG5)  # the merged folder isn't touched

    def test_as_4x(self):
        cfg = gguf_source.as_4x(self.CFG5)
        self.assertEqual(cfg, {"eos_token": "<|im_end|>", "additional_special_tokens": ["<|im_start|>", "<|im_end|>"],
                               "tokenizer_class": "Qwen2Tokenizer"})
        named = {"extra_special_tokens": {"image_token": "<img>"}, "additional_special_tokens": ["<x>"]}
        self.assertEqual(gguf_source.as_4x(named), named)  # already the 4.x form
        self.assertEqual(gguf_source.as_4x({"extra_special_tokens": [], "eos_token": "e"}), {"eos_token": "e"})
        self.assertIn("extra_special_tokens", self.CFG5)  # not changed in place

    def test_uses_the_base_tokenizer_when_the_vocabulary_matches(self):
        tok = json.loads(json.dumps(self.TOK))
        tok["model"]["merges"] = ["a b"]  # the older way of writing merges: same vocabulary
        snap = self.cache_base(tok)
        how, err = self.build()
        self.assertIn("the base model's", how)
        self.assertIn(snap, how)
        self.assertEqual(err, "")
        self.assertEqual(json.loads(self.read_out("tokenizer_config.json")), self.CFG4)
        self.assertEqual(json.loads(self.read_out("tokenizer.json")), tok)
        self.assertEqual(self.read_out("vocab.json"), "vocab.json")
        for name in ("tokenizer.json", "tokenizer_config.json", "vocab.json", "merges.txt"):
            self.assertFalse(os.path.islink(os.path.join(self.out, name)), name)  # copies, not links into the cache
        self.assert_weights_linked()

    def test_falls_back_when_the_base_vocabulary_differs(self):
        tok = json.loads(json.dumps(self.TOK))
        tok["model"]["vocab"]["ba"] = 4
        self.cache_base(tok)
        how, err = self.build()
        self.assertIn("doesn't match", err)
        self.assertIn("the merged model's", how)
        self.assertIn("4.x form", how)
        cfg = json.loads(self.read_out("tokenizer_config.json"))
        self.assertEqual(cfg["additional_special_tokens"], ["<|im_start|>", "<|im_end|>"])
        self.assertNotIn("extra_special_tokens", cfg)
        self.assertEqual(json.loads(self.read_out("tokenizer.json")), self.TOK)
        self.assertFalse(os.path.exists(os.path.join(self.out, "vocab.json")))
        self.assert_weights_linked()

    def test_base_files_written_by_5x_are_put_in_the_4x_form(self):
        self.cache_base(self.TOK, extra=(), cfg=self.CFG5)
        how, _err = self.build()
        self.assertIn("the base model's", how)
        self.assertIn("tokenizer_config.json (put in the transformers 4.x form)", how)
        self.assertEqual(json.loads(self.read_out("tokenizer_config.json")), gguf_source.as_4x(self.CFG5))

    def test_falls_back_without_the_base_files_and_rebuilds(self):
        for _ in range(2):  # the second run replaces the folder
            how, _err = self.build()
            self.assertIn("4.x form", how)
            self.assertNotIn("extra_special_tokens", json.loads(self.read_out("tokenizer_config.json")))
            self.assert_weights_linked()

    def test_no_merged_model(self):
        os.remove(os.path.join(self.fused, "config.json"))
        with self.assertRaises(SystemExit):
            self.build()


class MlxRequirementsTests(unittest.TestCase):
    def test_pinned(self):
        path = os.path.join(_paths.HERE, "train", "mlx-requirements.txt")
        with open(path) as f:
            lines = [ln.strip() for ln in f if ln.strip() and not ln.startswith("#")]
        self.assertTrue(all(re.fullmatch(r"[a-z0-9._-]+==[0-9][0-9A-Za-z.+-]*", ln) for ln in lines), lines)
        names = {ln.split("==")[0] for ln in lines}
        self.assertLessEqual({"mlx", "mlx-lm", "mlx-metal", "transformers", "tokenizers", "numpy"}, names)
        self.assertNotIn("torch", names)


class LatestSummaryTests(unittest.TestCase):
    def test_skips_experiments_and_partial_runs(self):
        tmp = tempfile.mkdtemp(prefix="hm-sum-")
        self.addCleanup(shutil.rmtree, tmp, True)
        runs = os.path.join(tmp, "results", "runs")
        def run(name, **meta):
            d = os.path.join(runs, name)
            os.makedirs(d)
            m = {"model": "m:1", "eval_version": "v1.1", "think": "unset", "limit": 0, "jobs": ["planner", "reviewer", "gate"]}
            m.update(meta)
            with open(os.path.join(d, "summary.json"), "w") as f:
                json.dump({"meta": m, "summary": {"name": name}}, f)
        run("20261028-100000-m-1")
        run("20261028-110000-m-1-check-first", variant="check-first", jobs=["reviewer"])
        run("20261028-120000-m-1", jobs=["reviewer"])
        run("20261028-130000-m-1-think", think="false")
        with mock.patch.object(summarize, "HERE", tmp):
            self.assertEqual(summarize.latest_summary("m:1", "v1.1")["summary"]["name"], "20261028-100000-m-1")


